const normalize = (s: string) => s.replace(/\s+/g, ' ').trim();
const forward = new Map(Object.entries(labels).map(([a, b]) => [normalize(a).toLowerCase(), b]));
const reverse = new Map(Object.entries(labels).map(([a, b]) => [normalize(b), a]));
export function translateLabel(text: string, language: string) {
  const match = text.match(/^(\s*)(.*?)(\s*)$/s)!;
  let value = match[2];
  const shortcut = value.match(/^(.*?)(\s*\((?:Ctrl|Shift|Alt|Esc|Mod|⌘|Delete|Tab|[A-Z]\+).*\))$/);
  const core = shortcut ? shortcut[1] : value;
  const canonical = reverse.get(normalize(core)) ?? core;
  value = language === 'en' ? canonical : (forward.get(normalize(canonical).toLowerCase()) ?? canonical);
  return match[1] + value + (shortcut?.[2] ?? '') + match[3];
}
export function localizeEditor(root: HTMLElement, language: string) {
  const originals = new WeakMap<Node, { original: string; last: string }>();
  const attributes = new WeakMap<Element, Map<string, { original: string; last: string }>>();
  let locale = language;
  const observer = new MutationObserver(update);
  function update() {
    observer.disconnect();
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node: Node | null;
    while ((node = walker.nextNode())) {
      if (node.parentElement?.closest('script,style,textarea,svg,[contenteditable]')) continue;
      const old = originals.get(node);
      const original = old && (node.nodeValue === old.last || node.nodeValue === old.original) ? old.original : node.nodeValue || '';
      const last = translateLabel(original, locale);
      if (node.nodeValue !== last) node.nodeValue = last;
      originals.set(node, { original, last });
    }
    for (const element of root.querySelectorAll('[title],[aria-label],[placeholder],input[type="button"],input[type="submit"],input[type="reset"]')) {
      const map = attributes.get(element) ?? new Map();
      const attrs = ['title', 'aria-label', 'placeholder'];
      if (element.matches('input[type="button"],input[type="submit"],input[type="reset"]')) attrs.push('value');
      for (const attribute of attrs) {
        const value = element.getAttribute(attribute); if (value === null) continue;
        const old = map.get(attribute);
        const original = old && (value === old.last || value === old.original) ? old.original : value;
        const last = translateLabel(original, locale);
        if (value !== last) element.setAttribute(attribute, last);
        map.set(attribute, { original, last });
      }
      attributes.set(element, map);
    }
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['title', 'aria-label', 'placeholder', 'value'] });
  }
  update();
  return { setLanguage(next: string) { locale = next; update(); }, dispose() { observer.disconnect(); } };
}
