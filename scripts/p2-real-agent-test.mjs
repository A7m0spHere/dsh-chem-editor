import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const log = await readFile('test-results/p2-live-runtime.log', 'utf8');
const url = log.match(/dsh web:\s*(https?:\/\/[^\s]+)/)?.[1];
if (!url) throw new Error('DSH launch URL unavailable');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1050 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
let f;
try {
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  const continueButton = page.getByRole('button', { name: '继续', exact: true });
  await continueButton.waitFor({ timeout: 5000 }).then(() => continueButton.click()).catch(() => {});
  await page.getByText('chem-', { exact: true }).first().hover();
  const create = page.getByRole('button', { name: /在.*chem-.*新建会话/ });
  await create.waitFor({ timeout: 30000 }); await create.click();
  await page.locator('[contenteditable="true"]').waitFor();
  console.log('LIVE session created; configured model:', await page.locator('button').evaluateAll(nodes => nodes.map(n => n.getAttribute('aria-label') || '').filter(s => s.includes('模型'))));
  await page.locator('[contenteditable="true"]').fill('本会话用于 dsh-chem-editor P2 集成验证。请只回复“准备好了”，不要调用任何工具。');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.getByText('准备好了', { exact: true }).last().waitFor({ timeout: 180000 });
  await page.getByRole('button', { name: '打开分子编辑器', exact: true }).click();
  await page.locator('iframe[title="分子编辑器"]').waitFor(); f = await (await page.locator('iframe[title="分子编辑器"]').elementHandle()).contentFrame();
  await f.waitForFunction(() => window.chemP0?.ketcher.editor.struct().atoms.size === 6 && document.querySelector('[data-save-status]')?.textContent === '已保存');
  const original = await f.evaluate(() => window.chemP0.fingerprint());
  const point = await f.evaluate(() => window.chemP0.atomPoint(1)); const rect = await page.locator('iframe[title="分子编辑器"]').boundingBox();
  await page.mouse.click(rect.x + point.x, rect.y + point.y);
  await f.getByLabel('对选区的批注').fill('把选中的碳原子替换为氮原子，其他原子和键保持。');
  await f.getByRole('button', { name: '交给 Agent', exact: true }).click();
  console.log('LIVE annotation submitted to configured DSH Agent');
  await f.locator('[data-preview-id]').waitFor({ timeout: 240000 });
  const id = await f.locator('[data-preview-id]').getAttribute('data-preview-id');
  assert.deepEqual(await f.evaluate(() => window.chemP0.fingerprint()), original);
  await page.screenshot({ path: 'test-results/p2-real-agent-preview.png' });
  await f.getByRole('button', { name: '应用修改', exact: true }).click();
  await f.locator('[data-annotation-status="applied"]').waitFor();
  await f.waitForFunction(() => document.querySelector('[data-save-status]')?.textContent === '已保存');
  const expected = structuredClone(original); expected.atoms.find(([id]) => id === 1)[1].label = 'N';
  assert.deepEqual(await f.evaluate(() => window.chemP0.fingerprint()), expected);
  await page.screenshot({ path: 'test-results/p2-real-agent-applied.png' });
  await f.getByRole('button', { name: '撤销', exact: true }).click();
  await f.waitForFunction(() => document.querySelector('[data-save-status]')?.textContent === '已保存');
  assert.deepEqual(await f.evaluate(() => window.chemP0.fingerprint()), original);
  await writeFile('test-results/p2-real-agent.json', JSON.stringify({ date: new Date().toISOString(), runtime: 'official DSH 0.2.0-rc.2', profile: 'chem-editor-p2-check-20261005', annotationId: id, previewRetainedOriginal: true, appliedOnlyFrozenAtom: true, undoRestoredOriginal: true, browserErrors: errors }, null, 2));
  assert.deepEqual(errors, []);
  console.log('ALL-PASS: P2 real DSH Agent preview/apply/save/undo');
} catch (e) {
  await page.screenshot({ path: 'test-results/p2-real-agent-failure.png' });
  console.log('LIVE diagnostic:', (await page.locator('body').innerText()).slice(-2600).replace(/(?:sk-|gho_)[A-Za-z0-9_-]+/g, '[redacted]'));
  throw e;
} finally { await browser.close(); }
